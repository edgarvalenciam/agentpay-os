-- Immutable commercial evidence; operational state is stored on Order, not its snapshot.
CREATE TRIGGER snapshot_no_update BEFORE UPDATE ON "OrderSnapshot"
BEGIN SELECT RAISE(ABORT, 'IMMUTABLE_SNAPSHOT'); END;
CREATE TRIGGER consent_no_update BEFORE UPDATE ON "ConsentRecord"
BEGIN SELECT RAISE(ABORT, 'IMMUTABLE_CONSENT'); END;
CREATE TRIGGER audit_no_update BEFORE UPDATE ON "AuditEvent"
BEGIN SELECT RAISE(ABORT, 'IMMUTABLE_AUDIT'); END;
CREATE TRIGGER audit_no_delete BEFORE DELETE ON "AuditEvent"
BEGIN SELECT RAISE(ABORT, 'IMMUTABLE_AUDIT'); END;
-- Every unresolved attempt occupies exactly its order's active slot.
CREATE TRIGGER attempt_slot_insert BEFORE INSERT ON "PaymentAttempt"
WHEN (NEW.status IN ('CREATED','SUBMISSION_PENDING','SUBMISSION_UNKNOWN','SUBMITTED','PAYMENT_PENDING','RECONCILIATION_EXCEPTION')
      AND (NEW.activeSlot IS NULL OR NEW.activeSlot != NEW.orderId))
 OR (NEW.status IN ('CONFIRMED','CANCELLED_LOCALLY') AND NEW.activeSlot IS NOT NULL)
 OR NEW.status NOT IN ('CREATED','SUBMISSION_PENDING','SUBMISSION_UNKNOWN','SUBMITTED','PAYMENT_PENDING','RECONCILIATION_EXCEPTION','CONFIRMED','CANCELLED_LOCALLY')
BEGIN SELECT RAISE(ABORT, 'INVALID_ACTIVE_SLOT'); END;
CREATE TRIGGER attempt_slot_update BEFORE UPDATE ON "PaymentAttempt"
WHEN (NEW.status IN ('CREATED','SUBMISSION_PENDING','SUBMISSION_UNKNOWN','SUBMITTED','PAYMENT_PENDING','RECONCILIATION_EXCEPTION')
      AND (NEW.activeSlot IS NULL OR NEW.activeSlot != NEW.orderId))
 OR (NEW.status IN ('CONFIRMED','CANCELLED_LOCALLY') AND NEW.activeSlot IS NOT NULL)
 OR NEW.status NOT IN ('CREATED','SUBMISSION_PENDING','SUBMISSION_UNKNOWN','SUBMITTED','PAYMENT_PENDING','RECONCILIATION_EXCEPTION','CONFIRMED','CANCELLED_LOCALLY')
BEGIN SELECT RAISE(ABORT, 'INVALID_ACTIVE_SLOT'); END;
